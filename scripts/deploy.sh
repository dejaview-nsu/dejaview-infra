#!/usr/bin/env bash

set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

if [[ $# -ne 3 ]]; then
    echo "Usage: $0 <backend-tag> <frontend-tag> <ml-tag>"
    exit 1
fi

TARGET_BACKEND_TAG="$1"
TARGET_FRONTEND_TAG="$2"
TARGET_ML_TAG="$3"

ENV_FILE="$ROOT_DIR/.env"
STATE_DIR="$ROOT_DIR/.deploy"
CURRENT_RELEASE_FILE="$STATE_DIR/current.env"
PREVIOUS_RELEASE_FILE="$STATE_DIR/previous.env"

TLS_DOMAIN="dev.deja-view.ru"

if [[ ! -f "$ENV_FILE" ]]; then
    echo "Error: $ENV_FILE does not exist"
    exit 1
fi

validate_tag() {
    local tag="$1"

    if [[ ! "$tag" =~ ^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$ ]]; then
        echo "Error: invalid image tag: $tag"
        return 1
    fi

    if [[ "$tag" == "latest" ]]; then
        echo "Error: 'latest' cannot be used for deploy/rollback"
        return 1
    fi
}

validate_app_environment() {
    local compose_environment
    local variable
    local missing=false

    if ! compose_environment="$("${COMPOSE[@]}" config --environment)"; then
        echo "Error: failed to resolve Docker Compose environment"
        return 1
    fi

    for variable in APP_URL SMTP_URL SMTP_FROM; do
        if ! awk -v key="$variable" '
            index($0, key "=") == 1 {
                value = substr($0, length(key) + 2)
                gsub(/^[[:space:]]+|[[:space:]]+$/, "", value)

                if (length(value) > 0) {
                    found = 1
                }
            }
            END { exit !found }
        ' <<< "$compose_environment"; then
            echo "Error: $variable is required for the app profile"
            missing=true
        fi
    done

    [[ "$missing" == false ]]
}

set_release_tags() {
    BACKEND_TAG="$1"
    FRONTEND_TAG="$2"
    ML_TAG="$3"
    export BACKEND_TAG FRONTEND_TAG ML_TAG
}

load_release_file() {
    local release_file="$1"
    local variable_prefix="$2"
    local BACKEND_TAG=""
    local FRONTEND_TAG=""
    local ML_TAG=""

    # Release files are generated by this script and contain only validated tags.
    source "$release_file"

    if [[ -z "$BACKEND_TAG" || -z "$FRONTEND_TAG" || -z "$ML_TAG" ]]; then
        echo "Error: incomplete release state in $release_file"
        return 1
    fi

    validate_tag "$BACKEND_TAG" || return 1
    validate_tag "$FRONTEND_TAG" || return 1
    validate_tag "$ML_TAG" || return 1

    printf -v "${variable_prefix}_BACKEND_TAG" '%s' "$BACKEND_TAG"
    printf -v "${variable_prefix}_FRONTEND_TAG" '%s' "$FRONTEND_TAG"
    printf -v "${variable_prefix}_ML_TAG" '%s' "$ML_TAG"
}

write_release_file() {
    local release_file="$1"
    local backend_tag="$2"
    local frontend_tag="$3"
    local ml_tag="$4"
    local temporary_file

    temporary_file="$(mktemp "$STATE_DIR/.release.XXXXXX")"

    if ! printf 'BACKEND_TAG=%s\nFRONTEND_TAG=%s\nML_TAG=%s\n' \
        "$backend_tag" "$frontend_tag" "$ml_tag" \
        > "$temporary_file"; then

        rm -f "$temporary_file"
        return 1
    fi

    if ! mv "$temporary_file" "$release_file"; then
        rm -f "$temporary_file"
        return 1
    fi
}

wait_for_health() {
    local name="$1"
    local timeout_seconds="$2"
    shift 2

    local deadline=$((SECONDS + timeout_seconds))

    while (( SECONDS < deadline )); do
        if "$@" >/dev/null 2>&1; then
            echo "$name is healthy"
            return 0
        fi

        echo "Waiting for $name..."
        sleep 2
    done

    echo "Error: $name healthcheck failed after ${timeout_seconds}s"
    return 1
}

start_or_restart_nginx() {
    if "${COMPOSE[@]}" ps --status running --services | grep -qx nginx; then
        echo "Restarting nginx..."
        "${COMPOSE[@]}" restart nginx || return 1
    else
        echo "Starting nginx..."
        "${COMPOSE[@]}" up -d nginx || return 1
    fi
}

activate_release() {
    "${COMPOSE[@]}" up -d --no-deps backend frontend ml || return 1
    start_or_restart_nginx || return 1
}

check_application_health() {
    local backend_address

    backend_address="$("${COMPOSE[@]}" port backend 8081)" || return 1

    wait_for_health "backend" 60 \
        curl -fsS --connect-timeout 2 --max-time 5 \
        "http://${backend_address}/health" || return 1

    wait_for_health "ml" 600 \
        "${COMPOSE[@]}" exec -T ml python -c \
        'import urllib.request; assert urllib.request.urlopen("http://127.0.0.1:8000/health", timeout=5).status == 200' \
        || return 1

    wait_for_health "frontend via HTTPS" 60 \
        curl -fsS --connect-timeout 2 --max-time 5 \
        "https://${TLS_DOMAIN}/" || return 1
}

restore_current_release() {
    echo "Restoring the last successful release..."
    set_release_tags \
        "$OLD_BACKEND_TAG" \
        "$OLD_FRONTEND_TAG" \
        "$OLD_ML_TAG"

    activate_release || return 1

    echo "Checking restored release health..."
    check_application_health || return 1
}

recover_failed_deploy() {
    if [[ "$HAS_CURRENT_RELEASE" == true ]]; then
        if restore_current_release; then
            echo "The last successful release was restored"
            return 0
        fi

        echo "Critical: new release failed and the last successful release could not be restored"
        return 1
    fi

    echo "No successful release is available; stopping application containers..."
    "${COMPOSE[@]}" stop backend frontend ml >/dev/null 2>&1 || true
}

commit_release_state() {
    local previous_backup=""
    local previous_existed=false

    if [[ "$HAS_CURRENT_RELEASE" == true ]]; then
        if [[ -f "$PREVIOUS_RELEASE_FILE" ]]; then
            previous_backup="$(mktemp "$STATE_DIR/.previous.env.XXXXXX")" \
                || return 1

            if ! cp "$PREVIOUS_RELEASE_FILE" "$previous_backup"; then
                rm -f "$previous_backup"
                return 1
            fi

            previous_existed=true
        fi

        if ! write_release_file \
            "$PREVIOUS_RELEASE_FILE" \
            "$OLD_BACKEND_TAG" \
            "$OLD_FRONTEND_TAG" \
            "$OLD_ML_TAG"; then

            [[ -z "$previous_backup" ]] || rm -f "$previous_backup"
            return 1
        fi
    fi

    if ! write_release_file \
        "$CURRENT_RELEASE_FILE" \
        "$TARGET_BACKEND_TAG" \
        "$TARGET_FRONTEND_TAG" \
        "$TARGET_ML_TAG"; then

        if [[ "$HAS_CURRENT_RELEASE" == true ]]; then
            if [[ "$previous_existed" == true ]]; then
                if ! mv "$previous_backup" "$PREVIOUS_RELEASE_FILE"; then
                    echo "Critical: failed to restore previous release state"
                fi
                previous_backup=""
            elif ! rm -f "$PREVIOUS_RELEASE_FILE"; then
                echo "Critical: failed to restore previous release state"
            fi
        fi

        [[ -z "$previous_backup" ]] || rm -f "$previous_backup"
        return 1
    fi

    if [[ -n "$previous_backup" ]]; then
        rm -f "$previous_backup" || true
    fi

    return 0
}

ensure_tls_certificate() {
    if "${COMPOSE[@]}" run --rm --no-deps \
        --entrypoint /bin/sh certbot \
        -c "test -s /etc/letsencrypt/live/$TLS_DOMAIN/fullchain.pem && \
            test -s /etc/letsencrypt/live/$TLS_DOMAIN/privkey.pem" \
        >/dev/null 2>&1; then

        echo "TLS certificate already exists"
        return
    fi

    echo "TLS certificate not found. Starting bootstrap nginx..."

    "${COMPOSE[@]}" stop nginx certbot >/dev/null 2>&1 || true

    if ! "${COMPOSE[@]}" \
        --profile tls-bootstrap \
        up -d --wait nginx-bootstrap; then

        cleanup_tls_bootstrap
        echo "Error: failed to start bootstrap nginx"
        return 1
    fi

    trap cleanup_tls_bootstrap EXIT INT TERM

    echo "Requesting certificate from Let's Encrypt via webroot..."

    if ! "${COMPOSE[@]}" \
        --profile tls-bootstrap \
        run --rm --no-deps \
        --entrypoint certbot \
        certbot \
        certonly \
        --webroot \
        --webroot-path /var/www/certbot \
        --non-interactive \
        --agree-tos \
        --register-unsafely-without-email \
        -d "$TLS_DOMAIN"; then

        cleanup_tls_bootstrap
        trap - EXIT INT TERM

        echo "Error: failed to obtain TLS certificate"
        return 1
    fi

    cleanup_tls_bootstrap
    trap - EXIT INT TERM

    echo "TLS certificate obtained successfully"
}

cleanup_tls_bootstrap() {
    "${COMPOSE[@]}" \
        --profile tls-bootstrap \
        rm -sf nginx-bootstrap \
        >/dev/null 2>&1 || true
}

validate_tag "$TARGET_BACKEND_TAG"
validate_tag "$TARGET_FRONTEND_TAG"
validate_tag "$TARGET_ML_TAG"

mkdir -p "$STATE_DIR"

HAS_CURRENT_RELEASE=false
SAME_RELEASE=false
OLD_BACKEND_TAG=""
OLD_FRONTEND_TAG=""
OLD_ML_TAG=""

if [[ -f "$CURRENT_RELEASE_FILE" ]]; then
    load_release_file "$CURRENT_RELEASE_FILE" OLD
    HAS_CURRENT_RELEASE=true

    if [[ "$TARGET_BACKEND_TAG" == "$OLD_BACKEND_TAG" &&
          "$TARGET_FRONTEND_TAG" == "$OLD_FRONTEND_TAG" &&
          "$TARGET_ML_TAG" == "$OLD_ML_TAG" ]]; then
        SAME_RELEASE=true
    fi
fi

set_release_tags \
    "$TARGET_BACKEND_TAG" \
    "$TARGET_FRONTEND_TAG" \
    "$TARGET_ML_TAG"

COMPOSE=(
    docker compose
    --env-file "$ENV_FILE"
    --profile infra
    --profile app
    --profile ml
    --profile tls
)

echo "Validating required application environment..."
validate_app_environment

echo "Validating compose configuration..."
"${COMPOSE[@]}" config >/dev/null

echo "Pulling application images..."
"${COMPOSE[@]}" pull backend frontend ml

echo "Starting infrastructure..."
"${COMPOSE[@]}" up -d --wait postgres qdrant minio

echo "Initializing MinIO..."
"${COMPOSE[@]}" run --rm minio-init

echo "Ensuring TLS certificate..."
ensure_tls_certificate

echo "Starting application..."
if ! activate_release; then
    echo "Error: failed to activate the new release"
    recover_failed_deploy || true
    exit 1
fi

echo "Starting certificate renewal..."
if ! "${COMPOSE[@]}" up -d --no-deps certbot; then
    echo "Error: failed to start certificate renewal"

    if ! recover_failed_deploy; then
        echo "Critical: certificate renewal failed and the last successful release could not be restored"
    fi

    exit 1
fi

echo "Checking application health..."
if ! check_application_health; then
    echo "Error: new release healthcheck failed"
    recover_failed_deploy || true
    exit 1
fi

if [[ "$SAME_RELEASE" == true ]]; then
    echo "Release tags are unchanged; release history was not modified"
elif ! commit_release_state; then
    echo "Error: failed to update release state"

    if ! recover_failed_deploy; then
        echo "Critical: release state update failed and the last successful release could not be restored"
    fi

    exit 1
fi

echo
echo "Deployment finished successfully."
"${COMPOSE[@]}" ps
